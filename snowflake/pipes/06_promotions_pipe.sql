USE DATABASE TAXI_DW;
USE SCHEMA RAW;

CREATE OR REPLACE PIPE PROMOTIONS_PIPE
    AUTO_INGEST = TRUE
    AS
    COPY INTO PROMOTIONS_RAW
    FROM @TAXI_S3_STAGE/promotions/
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    INCLUDE_METADATA = (
        SOURCE_FILE_NAME = METADATA$FILENAME,
        SOURCE_FILE_PATH = METADATA$FILENAME,
        SOURCE_ROW_NUMBER = METADATA$FILE_ROW_NUMBER,
        INGESTED_AT = METADATA$START_SCAN_TIME,
        RECORD_HASH = METADATA$FILE_CONTENT_KEY
    )
    FILE_FORMAT = (
        FORMAT_NAME = 'TAXI_CSV_FORMAT'
    );